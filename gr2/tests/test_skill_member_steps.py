"""The agent guide's member steps are git, as the verb table's row A rules: inside a member you use git.

Until this file, the guide (``api/skill.intro.md``, from which ``api/skill.md`` and ``gr2/AGENT_GUIDE.md`` are
generated) told an agent to run ``gr2 branch``, ``gr2 add`` and ``gr2 commit`` inside a member checkout, and
``gr2 add`` there refuses at exit 2 ("use git add here"). Recipe 1 run as written stopped at its first
``gr2 add``, in a compat store and in a full-mode root alike, and no member got its commit.

These rows read the guide's own text: one runs Recipe 1 as the page prints it, so the row tests the words an agent
reads, not a copy of them.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

GR2 = Path(__file__).resolve().parents[1]
INTRO = GR2 / "api" / "skill.intro.md"
SKILL = GR2 / "api" / "skill.md"
MARKER = "<!-- Generated by gr2/scripts/dump_skill.py"
MEMBER_VERB = re.compile(r"\bgr2 (add|commit|branch)\b")

ENV = {"GIT_AUTHOR_NAME": "x", "GIT_AUTHOR_EMAIL": "x@x", "GIT_COMMITTER_NAME": "x", "GIT_COMMITTER_EMAIL": "x@x",
       "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1", "GIT_TERMINAL_PROMPT": "0",
       "GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": "protocol.file.allow", "GIT_CONFIG_VALUE_0": "always"}


def recipe(text: str, heading: str) -> str:
    """The first ```bash block after `heading`; raises when the heading or its block is missing."""
    i = text.find(heading)
    if i < 0:
        raise LookupError(f"{heading!r} not found in the guide")
    m = re.search(r"```bash\n(.*?)```", text[i:], re.S)
    if not m:
        raise LookupError(f"no bash block after {heading!r}")
    return m.group(1)


def member_rows(text: str) -> list[str]:
    """Verb-map rows whose place is a member checkout."""
    return [ln for ln in text.splitlines() if ln.startswith("|") and "(member checkout" in ln]


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True,
                          env={**os.environ, **ENV}).stdout.strip()


def test_the_recipe_extractor_refuses_a_missing_heading():
    text = INTRO.read_text(encoding="utf-8")
    with pytest.raises(LookupError):
        recipe(text.replace("### Recipe 1:", "### Recipe one:"), "### Recipe 1:")
    with pytest.raises(LookupError):
        recipe("### Recipe 1: x\n\nno block here\n", "### Recipe 1:")


@pytest.mark.parametrize("mode", ["compat", "full"])
def test_recipe_1_runs_as_written_and_commits_in_each_member(tmp_path: Path, mode: str):
    gr2_bin = Path(sys.executable).parent / "gr2"
    assert gr2_bin.is_file(), f"no gr2 console script beside {sys.executable}; install gr2 into this venv"
    env = {**os.environ, **ENV, "PATH": f"{gr2_bin.parent}{os.pathsep}{os.environ.get('PATH', '')}"}
    urls = []
    for name in ("alpha", "beta"):
        src = tmp_path / f"seed-{name}"
        src.mkdir()
        git(src, "init", "-q", "-b", "main")
        (src / "README").write_text(f"{name}\n")
        git(src, "add", "README")
        git(src, "commit", "-q", "-m", f"seed {name}")
        url = tmp_path / f"{name}.git"
        git(tmp_path, "clone", "-q", "--bare", str(src), str(url))
        urls.append(f"{name}={url}")
    ws = tmp_path / "ws"
    init = subprocess.run([str(gr2_bin), "store", "init", str(ws), "--mode", mode,
                           "--clone", urls[0], "--clone", urls[1]], capture_output=True, text=True, env=env)
    assert init.returncode == 0, init.stderr
    before = {m: git(ws / m, "rev-list", "--count", "HEAD") for m in ("alpha", "beta")}

    script = recipe(INTRO.read_text(encoding="utf-8"), "### Recipe 1:")
    edited, n = re.subn(r"^WS=/path/to/workspace\b", f"WS={ws}", script, flags=re.M)
    assert n == 1, "Recipe 1 no longer sets WS on one EDIT line"
    run = subprocess.run(["bash", "-c", edited], capture_output=True, text=True, env=env, cwd=tmp_path)

    assert run.returncode == 0, (run.stdout, run.stderr)
    for m in ("alpha", "beta"):
        assert int(git(ws / m, "rev-list", "--count", "HEAD")) == int(before[m]) + 1, m
        assert git(ws / m, "show", "-s", "--format=%s", "HEAD") == f"{m}: work in progress (not pushed)"


def test_member_rows_of_the_verb_map_name_git_not_gr2():
    rows = member_rows(INTRO.read_text(encoding="utf-8"))
    assert len(rows) == 2, rows
    for row in rows:
        assert not MEMBER_VERB.search(row), row
        assert "`git " in row, row


def test_the_review_flow_pushes_member_branches_with_git():
    text = INTRO.read_text(encoding="utf-8")
    step = [ln for ln in text.splitlines() if re.match(r"3\. .*each member's branch", ln)]
    assert len(step) == 1, step
    assert "`git push`" in step[0] and "`gr2 push`" not in step[0], step[0]


def test_gr2_add_commit_branch_live_only_in_the_generated_reference():
    """Every `gr2 add`, `gr2 commit` and `gr2 branch` in the guide is below the generated-reference marker. The
    hand-written part names none: at this version gr2 add at a root takes a url, and the guide never adds a member."""
    intro = INTRO.read_text(encoding="utf-8")
    assert MEMBER_VERB.findall(intro) == [], [ln for ln in intro.splitlines() if MEMBER_VERB.search(ln)]
    skill = SKILL.read_text(encoding="utf-8")
    head, sep, reference = skill.partition(MARKER)
    assert sep, "the generated-reference marker is missing from api/skill.md"
    assert MEMBER_VERB.findall(head) == []
    allowed = ["### gr2 branch", "### gr2 add", "### gr2 commit"]
    found = [ln for ln in reference.splitlines() if MEMBER_VERB.search(ln)]
    assert found == allowed, found
