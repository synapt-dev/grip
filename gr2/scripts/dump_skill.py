#!/usr/bin/env python3
"""Generate ``api/skill.md``, an agent skill for gr2's review flow, from gr2's own code.

A hand-written skill drifts: a default the code changed, a refusal whose next step the
skill never named. So the parts that can be read from the code are read from it: each
verb's help line, each option with its help and its DEFAULT, and, for every refusal code
gr2 prints, the exact next step it prints beside it (``gr2/python_cli/next_steps.py``).
Only the short framing at the top is hand-written, in ``api/skill.intro.md``.

The gate is ``tests/test_skill_dump.py``: the committed file must equal what this renders
now, so a change to a verb, a default or a next step changes the skill in the same PR.

Run from ``gr2/``: ``python scripts/dump_skill.py > api/skill.md``.
"""
from __future__ import annotations

import ast
import inspect
import sys
from pathlib import Path

GR2 = Path(__file__).resolve().parents[1]
if str(GR2) not in sys.path:
    sys.path.insert(0, str(GR2))

import typer  # noqa: E402

from gr2 import api_core  # noqa: E402
from gr2.python_cli import next_steps  # noqa: E402
from gr2.python_cli.app import app  # noqa: E402

INTRO = GR2 / "api" / "skill.intro.md"

# The review flow, in the order an operator meets it. A curated list, not the whole app:
# the skill is for one job.
VERBS = ["store init", "review pin", "push", "review publish", "review receive", "review stamp",
         "check run", "check show", "review merge"]
NO_HELP = "(no help text in the code)"


def _default(value: object) -> str:
    if value in (None, False, "", (), []):
        return ""
    if isinstance(value, (list, tuple)):
        return f" [default: {', '.join(map(str, value))}]"
    return f" [default: {value}]"


def verb_lines(cmd, verb: str) -> list[str]:
    help_line = (cmd.help or "").strip().splitlines()[0] if cmd.help else NO_HELP
    lines = [f"### gr2 {verb}", "", help_line, ""]
    for param in cmd.params:
        if param.param_type_name == "argument":
            lines.append(f"- `<{param.name}>`{'' if param.required else ' (optional)'}")
        else:
            text = " ".join((param.help or "").split()) or NO_HELP
            lines.append(f"- `{'/'.join(param.opts)}`{_default(param.default)}: {text}")
    return lines + [""]


def _placeholders(fn) -> dict[str, object]:
    """Placeholder arguments for a next-step function: `<name>` for each required one."""
    out: dict[str, object] = {}
    for name, param in inspect.signature(fn).parameters.items():
        if param.default is inspect.Parameter.empty:
            out[name] = ("test",) if name == "checks" else f"<{name}>"
    return out


def _dispatch_codes(fn) -> tuple[list[str], str | None]:
    """The refusal-code prefixes a dispatcher tests with
    ``<first parameter>.startswith("...")``, in source order."""
    first = next(iter(inspect.signature(fn).parameters), None)
    if first is None:
        return [], None
    found = []
    for node in ast.walk(ast.parse(inspect.getsource(fn))):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                and node.func.attr == "startswith"
                and isinstance(node.func.value, ast.Name) and node.func.value.id == first
                and node.args and isinstance(node.args[0], ast.Constant)):
            found.append((node.lineno, node.args[0].value))
    return [code for _, code in sorted(found)], first


def refusal_rows() -> list[tuple[str, str]]:
    """(code as printed, next step) for every public function in next_steps; a dispatcher
    gives one row per code it answers."""
    rows = []
    for name, fn in inspect.getmembers(next_steps, inspect.isfunction):
        if name.startswith("_") or fn.__module__ != next_steps.__name__:
            continue
        codes, first = _dispatch_codes(fn)
        args = _placeholders(fn)
        if codes:
            for code in codes:
                shown = code[:-1] + "*" if code.endswith("_") else code
                rows.append((shown, fn(**{**args, first: code})))
        else:
            rows.append((name, fn(**args)))
    return sorted(rows)


def render() -> str:
    root = typer.main.get_command(app)
    by_path = {" ".join(path): cmd for path, cmd, _ in api_core.walk(root)}
    out = [INTRO.read_text(encoding="utf-8").rstrip("\n"), "",
           "<!-- Generated by gr2/scripts/dump_skill.py from gr2's own code; "
           "edit the code or skill.intro.md, not this file. -->", "", "## The verbs", ""]
    for verb in VERBS:
        cmd = by_path.get(verb)
        if cmd is None:
            raise SystemExit(f"dump_skill: `gr2 {verb}` is not in the app; update VERBS")
        out += verb_lines(cmd, verb)
    out += ["## When gr2 prints `refused: <code>`", "",
            "gr2 names the next step beside the refusal; the same text is here, keyed by the "
            "code. A code ending in `*` covers every code that starts with it and has no row "
            "of its own.", ""]
    for code, text in refusal_rows():
        out += [f"### {code}", "", text, ""]
    return "\n".join(out).rstrip("\n") + "\n"


if __name__ == "__main__":
    sys.stdout.write(render())
